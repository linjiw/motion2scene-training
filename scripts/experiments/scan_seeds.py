"""Build the burned-seed registry mechanically from local evidence.

Scans every workspace/**/command.json (Hydra ``++seed=`` overrides), JSON/YAML
configs with seed-like keys, and the traversal evaluation locks, then writes
experiments/seeds.yaml. Any seed found here must not be used as a held-out
evaluation seed. Usage: python scripts/experiments/scan_seeds.py [--root .]
"""

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

SEED_KEY = re.compile(r"(^|_)seed(s)?$")
HYDRA_SEED = re.compile(r"^\+*seed=(\d+)$")


def walk_json(obj, path, hits):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if SEED_KEY.search(str(k)):
                for s in (v if isinstance(v, list) else [v]):
                    if isinstance(s, int) and not isinstance(s, bool):
                        hits[s].add(path)
            walk_json(v, path, hits)
    elif isinstance(obj, list):
        for v in obj:
            walk_json(v, path, hits)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    p.add_argument("--out", type=Path)
    a = p.parse_args()
    root = a.root
    used = defaultdict(set)
    for f in (root / "workspace").rglob("command.json"):
        try:
            args = json.loads(f.read_text())
        except Exception:
            continue
        for x in args if isinstance(args, list) else []:
            m = HYDRA_SEED.match(str(x))
            if m:
                used[int(m.group(1))].add(str(f.relative_to(root)))
    for f in (root / "workspace").rglob("*.json"):
        # Skip bulky arrays/manifests; seeds live in small config/receipt files.
        if f.stat().st_size > 2_000_000 or "hydra" in f.parts:
            continue
        try:
            walk_json(json.loads(f.read_text()), str(f.relative_to(root)), used)
        except Exception:
            pass
    for f in (root / "workspace").rglob("*.yaml"):
        if f.stat().st_size > 2_000_000 or "hydra" in f.parts:
            continue
        for m in re.finditer(r"^\s*seed:\s*(\d+)\s*$", f.read_text(errors="ignore"), re.M):
            used[int(m.group(1))].add(str(f.relative_to(root)))
    reserved = defaultdict(set)
    for f in sorted((root / "docs").rglob("TRAVERSAL_EVALUATION_LOCK_*.json")):
        walk_json(json.loads(f.read_text()), str(f.relative_to(root)), reserved)
    # Doc-only seeds whose packets live on the other host.
    doc_only = {91201: "docs/sonic/motion2scene/SONIC_TRACKING_EVALUATION_20260912.md (seed 91201, packet on other host)"}
    out = a.out or root / "experiments" / "seeds.yaml"
    lines = ["# Generated by scripts/experiments/scan_seeds.py; do not edit by hand.",
             "# burned: used for collection, training or evaluation; never reuse as held-out.",
             "burned:"]
    # Experiment seeds (eval/collection/fit) are 5-6 digit by convention; very small
    # or 32-bit values are per-sample generation seeds and are counted, not listed.
    other = sorted(x for x in used if not 10_000 <= x < 1_000_000)
    for s in sorted({x for x in used if 10_000 <= x < 1_000_000} | set(doc_only)):
        srcs = sorted(used.get(s, set()))
        n = len(srcs)
        ex = srcs[0] if srcs else doc_only[s]
        lines.append(f"  {s}: {{uses: {n}, example: \"{ex}\"}}")
    lines.append(f"# {len(other)} other seed values (generation/sample seeds outside 10000-999999) omitted.")
    lines.append("reserved_by_locks:")
    for s in sorted(reserved):
        lines.append(f"  {s}: \"{sorted(reserved[s])[0]}\"")
    lines += [
        "blocks:",
        "  collection: [70000, 79999]",
        "  confirmation_nav8192: [92601, 92609]",
        "  dev: [92610, 92699]",
        "  confirmation: [92700, 92799]",
        "  test_sealed: [95000, 95099]",
    ]
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(used)} seed values from workspace, {len(reserved)} reserved by locks -> {out}")


if __name__ == "__main__":
    main()
